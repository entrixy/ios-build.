import Foundation

public struct AutomationReadiness: Equatable {
    public let template: AutomationTemplate
    public let evaluatedAt: Date
    public let observations: AutomationObservations
    public let matched: Bool
    public let routeMatched: Bool
    public let ready: Bool
    public let distanceM: Double?
    public func satisfies(_ candidate: AutomationTemplate, at date: Date) -> Bool {
        let age = date.timeIntervalSince(evaluatedAt)
        return candidate == template && age >= 0 && age <= 2 && matched
    }
}

/// GeoTracker's observation/dwell/entry state, independent from actuation.
/// No request, command, identity or journal entry is generated by evaluation.
public struct AutomationRuntime {
    private struct State {
        var observations: AutomationObservations
        var processedLocationMS: Int64?
        var lastGeoAt: TimeInterval?
        var distanceM: Double?
        var geoOrange: Bool?
        var previousMatched: Bool?
        var awaitEntry = false
        var armed = true
        var lastFire: TimeInterval?
        var matchStarted: TimeInterval?
        var template: AutomationTemplate
    }
    public let sessionStarted: TimeInterval
    private var states: [String: State] = [:]
    private var samples: [AutomationLocationFix] = []
    private var latest: AutomationLocationFix?
    private var routes = GeoCorridorMatcher()
    public init(sessionStarted: TimeInterval) { self.sessionStarted = sessionStarted }
    public mutating func reset(_ key: String) { states.removeValue(forKey: key); routes.reset(key) }
    public mutating func retain(_ keys: Set<String>) {
        for key in Array(states.keys) where !keys.contains(key) { reset(key) }
    }
    public mutating func receive(_ fix: AutomationLocationFix) {
        guard fix.isValid, latest.map({ fix.timestampMS > $0.timestampMS }) ?? true else { return }
        latest = fix; samples.append(fix)
        samples.removeAll { fix.timestampMS-$0.timestampMS > 45_000 }
        if samples.count > 5 { samples.removeFirst(samples.count-5) }
        while samples.count > 1, let first = samples.first, Self.distance(first.latitude,first.longitude,fix.latitude,fix.longitude) > 100 {
            samples.removeFirst()
        }
    }
    private func smoothed(now: TimeInterval) -> (latitude: Double,longitude: Double,accuracy: Double)? {
        let valid = samples.filter { (0.1...150).contains($0.accuracyM) && now-Double($0.timestampMS)/1000 <= 45 }
        guard let first = valid.first, valid.count >= 2 || first.accuracyM <= 50 else { return nil }
        var latitude = 0.0, longitude = 0.0, total = 0.0
        for fix in valid {
            let accuracy = Double(max(5,fix.accuracyM)), weight = 1/(accuracy*accuracy)
            latitude += fix.latitude*weight; longitude += fix.longitude*weight; total += weight
        }
        return (latitude/total,longitude/total,sqrt(1/total))
    }
    public mutating func evaluate(key: String, template: AutomationTemplate, date: Date,
                                 wifiMatches: Int? = nil, wifiRequired: Int? = nil,
                                 bleReady: Bool? = nil, calendar: Calendar = .current) -> AutomationReadiness {
        let now = date.timeIntervalSince1970
        if states[key]?.template != template { reset(key) }
        var state = states[key] ?? State(observations: AutomationObservations(sessionStarted: sessionStarted),template: template)
        defer { states[key] = state }
        state.observations.wifiMatches = wifiMatches; state.observations.wifiRequired = wifiRequired
        state.observations.bleReady = bleReady
        let geoActive = template.geoEnabled && template.geoLat != nil && template.geoLon != nil
        var physicallyOutside = false, routeMatched = false
        if geoActive, let latitude = template.geoLat, let longitude = template.geoLon,
           let fix = latest, now >= Double(fix.timestampMS)/1000, now-Double(fix.timestampMS)/1000 <= 30 {
            let raw = Self.distance(fix.latitude,fix.longitude,latitude,longitude)
            state.distanceM = raw; physicallyOutside = raw > Double(template.radiusM ?? 30)
            let smooth = smoothed(now: now)
            let distance = smooth.map { Self.distance($0.latitude,$0.longitude,latitude,longitude) } ?? raw
            let radius = Double(template.radiusM ?? 30)
            state.geoOrange = distance <= max(radius+250,300); state.lastGeoAt = Double(fix.timestampMS)/1000
            if template.geoMode == "route", !template.corridors.isEmpty {
                state.observations.geoMatched = false
                if state.processedLocationMS != fix.timestampMS {
                    routeMatched = routes.update(key:key,fix:fix,gate:AutomationGeoPoint(lat:latitude,lon:longitude),corridors:template.corridors)
                }
            } else if template.geoMode == "route" {
                state.observations.geoMatched = smooth != nil && distance <= Double(template.gateRadiusM ?? 20)
            } else {
                state.observations.geoMatched = smooth != nil && distance <= radius && (smooth?.accuracy ?? Double(fix.accuracyM)) <= max(radius/2,20)
            }
            state.processedLocationMS = fix.timestampMS
        } else if geoActive {
            // A timer without a valid fix cannot manufacture a new outside entry.
            // Nor can an old location satisfy a physical-command revalidation.
            if state.lastGeoAt.map({ now-$0 > 30 || now < $0 }) ?? true { state.observations.geoMatched = false }
        }
        let matched = AutomationEvaluation.matched(template,observations:state.observations,date:date,calendar:calendar)
        let wifiOrange = template.wifiEnabled && (wifiMatches ?? 0) > 0
        let timeOrange = template.timeEnabled && stride(from: 0, through: 300, by: 30).contains { AutomationEvaluation.timeReady(template,date:date.addingTimeInterval(Double($0)),calendar:calendar) }
        let anyOrange = (geoActive && state.geoOrange == true) || wifiOrange || timeOrange || (template.bleEnabled && bleReady == true)
        if state.previousMatched == nil && matched { state.awaitEntry = true }
        if !matched && state.awaitEntry && (physicallyOutside || !geoActive) { state.awaitEntry = false }
        if !anyOrange && (!geoActive || state.geoOrange != nil) {
            state.observations.lastOutsideOrange = now; state.armed = true; state.awaitEntry = false
            state.matchStarted = nil
        }
        if let last = state.lastFire, now >= last+180 { state.armed = true }
        state.previousMatched = matched
        if matched { if state.matchStarted == nil { state.matchStarted = now } }
        else { state.matchStarted = nil }
        let dwell = !geoActive || state.matchStarted.map({ now-$0 >= 10 }) == true
        let cooldown = state.lastFire.map({ now >= $0+180 }) ?? true
        let ready = routeMatched || (matched && state.armed && !state.awaitEntry && cooldown && dwell)
        return AutomationReadiness(template:template,evaluatedAt:date,observations:state.observations,matched:matched,routeMatched:routeMatched,ready:ready,distanceM:state.distanceM)
    }
    public mutating func consume(_ key: String, route: Bool, at date: Date) {
        routes.markOpened(key)
        guard !route, var state = states[key] else { return }
        state.armed = false; state.awaitEntry = true; state.lastFire = date.timeIntervalSince1970
        state.matchStarted = nil; states[key] = state
    }
    public static func distance(_ latitude: Double, _ longitude: Double, _ targetLat: Double, _ targetLon: Double) -> Double {
        let dlat = (targetLat-latitude)*Double.pi/180, dlon = (targetLon-longitude)*Double.pi/180
        let a = pow(sin(dlat/2),2)+cos(latitude*Double.pi/180)*cos(targetLat*Double.pi/180)*pow(sin(dlon/2),2)
        return 6_371_000*2*atan2(sqrt(max(0,a)),sqrt(max(0,1-a)))
    }
}
